// Regenerates the sky data. Run: node scripts/star-map-data.mjs
// Writes src/star-catalog.ts from NASA HEASARC BSC5P and downloads the ESA/Webb
// 300-pixel previews listed in src/star-data.ts to public/sky/webb/.
import { mkdir, writeFile } from 'node:fs/promises'
import { webbImages } from '../src/star-data.ts'

const LIMIT = 5.5
const query = `SELECT hr, name, alt_name, ra, dec, vmag, bv_color FROM bsc5p WHERE vmag <= ${LIMIT} ORDER BY hr`
const url = new URL('https://heasarc.gsfc.nasa.gov/xamin/vo/tap/sync')
for (const [key, value] of Object.entries({ REQUEST: 'doQuery', LANG: 'ADQL', QUERY: query })) url.searchParams.set(key, value)
const xml = await (await fetch(url)).text()
const stream = xml.match(/<STREAM encoding="base64">([\s\S]*?)<\/STREAM>/)
if (!stream) throw new Error(`Unexpected TAP response: ${xml.slice(0, 400)}`)

// Binary VOTable rows: short hr, char* name, char* alt_name, double ra/dec, float vmag/bv.
const bytes = Buffer.from(stream[1].replace(/\s+/g, ''), 'base64')
let offset = 0
const text = () => {
  const length = bytes.readInt32BE(offset); offset += 4
  const value = bytes.toString('latin1', offset, offset + length); offset += length
  return value
}
const rows = [], designations = new Map()
while (offset < bytes.length) {
  const hr = bytes.readInt16BE(offset); offset += 2
  text()
  const alt = text().trim().padStart(10)
  const ra = bytes.readDoubleBE(offset), dec = bytes.readDoubleBE(offset + 8); offset += 16
  const vmag = bytes.readFloatBE(offset), bv = bytes.readFloatBE(offset + 4); offset += 8
  rows.push(`${hr},${+ra.toFixed(4)},${+dec.toFixed(4)},${+vmag.toFixed(2)},${Number.isNaN(bv) ? 0.6 : +bv.toFixed(2)},`)
  // alt_name columns: Flamsteed (3), Bayer (3), superscript (1), constellation (3).
  const bayer = alt.slice(3, 6).trim(), sup = alt.slice(6, 7).trim(), con = alt.slice(7, 10)
  if (!bayer) continue
  // Double stars share a designation (Zet Ori is HR 1948 and 1949); keep the brighter row.
  const key = `${bayer}${sup} ${con}`, existing = designations.get(key)
  if (!existing || vmag < existing.vmag) designations.set(key, { hr, vmag })
}

await writeFile('src/star-catalog.ts', `/** Generated by scripts/star-map-data.mjs; do not edit.
 * NASA HEASARC BSC5P (Hoffleit & Warren 1991), every star with V <= ${LIMIT}.
 * Rows of STAR_ROW numbers: HR, RA J2000 deg, Dec J2000 deg, V magnitude, B-V.
 * A missing B-V is stored as 0.6 (a neutral white). */
export const STAR_ROW = 5

export const starRows: readonly number[] = [
${rows.join('\n')}
]

/** Bayer designation ("Alp Ori") to HR number; a double star keeps its brighter row. */
export const designations: Readonly<Record<string, number>> = {
${[...designations].map(([key, { hr }]) => `  '${key}': ${hr},`).join('\n')}
}
`)
console.log(`Wrote ${rows.length} stars and ${designations.size} designations.`)

await mkdir('public/sky/webb', { recursive: true })
for (const image of webbImages) {
  const response = await fetch(`https://cdn.esawebb.org/archives/images/thumb300y/${image.id}.jpg`)
  if (!response.ok) throw new Error(`${image.id}: HTTP ${response.status}`)
  await writeFile(`public/sky/webb/${image.id}.jpg`, Buffer.from(await response.arrayBuffer()))
}
console.log(`Downloaded ${webbImages.length} ESA/Webb previews.`)
